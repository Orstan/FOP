export async function POST(req: NextRequest) {
  try {
    const ip = req.headers.get('x-forwarded-for')?.split(',')[0]?.trim() || '127.0.0.1';
    if (!checkRateLimit(ip)) {
      return NextResponse.json(
        { error: 'Забагато запитів. Будь ласка, зачекайте кілька хвилин перед наступним зверненням.' },
        { status: 429 }
      );
    }

    const apiKey = process.env.OPENAI_API_KEY;
    if (!apiKey) {
      return NextResponse.json(
        {
          error: 'OPENAI_API_KEY не налаштовано в системі. Будь ласка, перевірте налаштування оточення на Vercel або у файлі .env.local.',
        },
        { status: 500 }
      );
    }

    const body = await req.json();
    const { messages = [] } = body;

    // Беремо останні 8 повідомлень для збереження контексту та економії токенів
    const recentMessages = Array.isArray(messages)
      ? messages.slice(-8).map((m: { role: string; content: string }) => ({
          role: m.role === 'user' ? 'user' : ('assistant' as const),
          content: String(m.content || ''),
        }))
      : [];

    const openai = new OpenAI({ apiKey });

    const completion = await openai.chat.completions.create({
      model: 'gpt-4o-mini',
      messages: [
        { role: 'system', content: SYSTEM_PROMPT },
        ...recentMessages,
      ],
      temperature: 0.5,
      stream: true,
    });

    const encoder = new TextEncoder();

    const stream = new ReadableStream({
      async start(controller) {
        try {
          for await (const chunk of completion) {
            const content = chunk.choices[0]?.delta?.content || '';
            if (content) {
              controller.enqueue(encoder.encode(content));
            }
          }
        } catch (err) {
          console.error('Stream error:', err);
          controller.error(err);
        } finally {
          controller.close();
        }
      },
    });

    return new Response(stream, {
      headers: {
        'Content-Type': 'text/plain; charset=utf-8',
        'Cache-Control': 'no-cache',
        'Transfer-Encoding': 'chunked',
      },
    });
  } catch (error: any) {
    console.error('AI Chat Error:', error);
    return NextResponse.json(
      { error: error?.message || 'Виникла помилка під час обробки запиту AI.' },
      { status: 500 }
    );
  }
}
