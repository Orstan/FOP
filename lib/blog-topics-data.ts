export function getBlogTopicBySlug(slug: string): BlogTopicData | undefined {
  return blogTopicsData.find(topic => topic.slug === slug);
}

export function getAllBlogTopicSlugs(): string[] {
  return blogTopicsData.map(topic => topic.slug);
}

export function getBlogTopicsByCategory(category: string): BlogTopicData[] {
  return blogTopicsData.filter(topic => topic.category === category);
}

export function getAllBlogCategories(): string[] {
  return Array.from(new Set(blogTopicsData.map(topic => topic.category)));
}
